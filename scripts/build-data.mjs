#!/usr/bin/env node
/**
 * Builds the two files the Morocco heat map runs on. Run it only when a
 * source changes; both outputs are committed.
 *
 *   src/data/morocco.topo.json     - 75 province shapes + the 12 regions
 *                                   dissolved from them (so they nest exactly),
 *                                   keyed by HCP code, simplified (~60 KB).
 *                                   Imported, not fetched: it ships in a JS
 *                                   chunk, so the map works offline.
 *   src/data/admin.ts - HCP regions and provinces, French + Arabic
 *                                   names (goes to the browser).
 *   src/data/communes.ts - the 1,503 communes with their centre
 *                                   point and urban-centre names (server only).
 *
 * Sources (download with `npm pack <pkg> && tar -xzf <tgz>`):
 *   morocco-map@1.3.0       data/provinces.json  ODbL-1.0, (c) OpenStreetMap
 *                           contributors. Morocco whole, south included.
 *   morocco-communes@1.9.1  dist/*.js            code MIT, data HCP RGPH 2024
 *                           (CC BY 4.0, credit the Haut-Commissariat au Plan).
 *   morocco-communes repo   data/v1/attributes/communes.json  centroids and
 *                           urban centres, OpenStreetMap-derived (ODbL).
 *                           Not in the npm package: take it from the repo.
 *
 * Usage:
 *   node scripts/build-data.mjs <morocco-map/package> <morocco-communes/package> <communes.json>
 *
 * Needs `npx mapshaper` (fetched on demand, not a dependency).
 */
import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"
import { pathToFileURL } from "node:url"
import { feature } from "topojson-client"

const [mapPkg, communesPkg, communesAttrs] = process.argv.slice(2)
if (!mapPkg || !communesPkg || !communesAttrs) {
  console.error("usage: build-morocco-map.mjs <morocco-map pkg dir> <morocco-communes pkg dir> <communes.json>")
  process.exit(1)
}

const load = async (file) => (await import(pathToFileURL(resolve(communesPkg, "dist", file)).href)).default
const regions = await load("regions.js")
const provinces = await load("provinces.js")
const communes = await load("communes.js")
const attrs = new Map(JSON.parse(readFileSync(communesAttrs, "utf8")).map((c) => [c.code, c]))

// Province names in the OSM file read "Province de Khémisset إقليم الخميسات";
// keep the French part and compare it loosely with HCP's French name.
const norm = (s) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z' -]/g, " ")
    .replace(/\b(prefecture|province)\s+(de|d'|of)?\s*/g, " ")
    .replace(/['-]/g, " ")
    .replace(/\s+/g, " ")
    .trim()

// The 8 Casablanca préfectures d'arrondissements sit inside Casablanca; the
// map draws Casablanca whole, so they are not shapes.
const shaped = provinces.filter((p) => p.type !== "prefecture_of_arrondissements")
const byName = new Map(shaped.map((p) => [norm(p.name.fr), p]))
// OSM spelling -> census spelling, both normalised.
const ALIASES = {
  "el kelaat es sraghna": "el kelaa des sraghna",
  mohammedia: "mohammadia",
  rhamna: "rehamna",
  taroudant: "taroudannt",
  "fquih ben saleh": "fquih ben salah",
  "agadir ida outanane": "agadir ida ou tanane",
}

const topo = JSON.parse(readFileSync(resolve(mapPkg, "data/provinces.json"), "utf8"))
const fc = feature(topo, topo.objects.provinces)
const seen = new Set()
for (const f of fc.features) {
  const raw = f.properties.name || ""
  let key = norm(raw)
  if (!key && raw.includes("الرباط")) key = "rabat"
  key = ALIASES[key] ?? key
  const p = byName.get(key)
  if (!p) throw new Error(`No HCP province for "${raw}" (normalised "${key}")`)
  if (seen.has(p.code)) throw new Error(`Two shapes for ${p.code} ${p.name.fr}`)
  seen.add(p.code)
  f.properties = { code: p.code, region: p.region }
}
const missing = shaped.filter((p) => !seen.has(p.code))
if (missing.length) throw new Error(`Provinces without a shape: ${missing.map((p) => p.name.fr).join(", ")}`)

const work = mkdtempSync(join(tmpdir(), "morocco-map-"))
const src = join(work, "provinces.geojson")
writeFileSync(src, JSON.stringify(fc))
mkdirSync("src/data", { recursive: true })
const out = "src/data/morocco.topo.json"
execFileSync(
  "npx",
  [
    "-y", "mapshaper@0.7",
    "-i", src, "name=provinces",
    "-simplify", "weighted", "12%", "keep-shapes",
    "-clean",
    "-dissolve", "region", "copy-fields=region", "+", "name=regions",
    "-each", "code=region", "target=regions",
    "-o", out, "format=topojson", "quantization=20000", "target=provinces,regions",
  ],
  { stdio: "inherit" }
)

const json = (v) => JSON.stringify(v)
const header = `// GENERATED by scripts/build-data.mjs - do not edit by hand.
// Haut-Commissariat au Plan, RGPH 2024 (CC BY 4.0), via morocco-communes@1.9.1.
// Trimmed to codes and names.
`
// Regions and provinces are small and go to the browser with the map.
writeFileSync(
  "src/data/admin.ts",
  `${header}
export const HCP_REGIONS: ReadonlyArray<{ code: string; fr: string; ar: string }> = ${json(
    regions.map((r) => ({ code: r.code, fr: r.name.fr, ar: r.name.ar }))
  )}

/** Casablanca's 8 préfectures d'arrondissements are left out: the map draws Casablanca whole. */
export const HCP_PROVINCES: ReadonlyArray<{ code: string; region: string; fr: string; ar: string }> = ${json(
    shaped.map((p) => ({ code: p.code, region: p.region, fr: p.name.fr, ar: p.name.ar }))
  )}
`
)
// Communes (~100 KB) are only for placing typed cities, on the server.
writeFileSync(
  "src/data/communes.ts",
  `${header}
/**
 * [commune code, province code, French name, Arabic name, 2024 population,
 *  longitude, latitude, urban-centre names]. The point is the commune's
 *  centroid, rounded to ~100 m; null for the one commune OSM has no shape for.
 */
export const HCP_COMMUNES: ReadonlyArray<
  readonly [string, string, string, string, number, number | null, number | null, readonly string[]]
> = ${json(
    communes.map((c) => {
      const extra = attrs.get(c.code)
      const round = (v) => (typeof v === "number" ? Math.round(v * 1000) / 1000 : null)
      return [
        c.code,
        c.province,
        c.name.fr,
        c.name.ar,
        c.population,
        round(extra?.centroid?.lng),
        round(extra?.centroid?.lat),
        (extra?.urbanCentres ?? []).map((u) => u.name).filter((n) => n && n !== c.name.fr),
      ]
    })
  )}
`
)
console.log(`provinces ${fc.features.length}, regions ${regions.length}, communes ${communes.length}`)
